#!/usr/bin/env python3
"""Sprocket Rally's icon: a 32x32 (and a 16x16) drawn here pixel by pixel, in the manner of a
1990s desktop icon: a small fixed palette, a black outline, hard shading, no smoothing.
Writes src/icon_data.h (for the window's icon), tools/sprocket.ico (for the Windows exe) and
tools/icon_preview.png."""
import math, os, struct, io
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
K = (0, 0, 0, 255)
PAL = dict(k=K, Y=(255, 224, 80, 255), y=(240, 168, 32, 255), o=(184, 104, 16, 255), W=(255, 255, 255, 255),
           g=(168, 168, 184, 255), R=(232, 56, 40, 255), r=(144, 24, 32, 255), b=(40, 72, 168, 255), B=(96, 152, 248, 255))

def draw(n):
    s = n / 32.0
    img = [[None] * n for _ in range(n)]
    cx, cy = 14.5 * s, 14.5 * s
    for y in range(n):
        for x in range(n):
            dx, dy = x + 0.5 - cx - 0.5 * s, y + 0.5 - cy - 0.5 * s
            r = math.hypot(dx, dy) / s
            a = math.atan2(dy, dx)
            tooth = math.cos(8 * a + 0.4) > 0.15
            if r <= (13.6 if tooth else 10.4):
                lit = (-dx - dy) / (s * 14.0)            # light from the top left
                c = 'Y' if lit > 0.25 else ('y' if lit > -0.35 else 'o')
                if r < 5.2: c = 'k'
                if r < 4.3: c = 'R' if lit > -0.1 else 'r'
                if r < 1.7: c = 'k'
                if 6.3 < r < 7.3 and lit <= 0.25: c = 'o'  # a groove round the hub
                img[y][x] = c
    if n >= 32:
        img[int(cy - 3)][int(cx - 2)] = 'W'                # a glint on the hub
        img[int(cy - 3)][int(cx - 1)] = 'W'
    # the chequered flag, low on the right, on its pole
    fx, fy, cell = int(19 * s), int(17 * s), max(2, int(3 * s))
    for y in range(fy, n - 1):
        for dxp in range(max(1, int(s))):
            if fx + dxp < n: img[y][fx + dxp] = 'g'
    for j in range(3):
        for i in range(4):
            for yy in range(cell):
                for xx in range(cell):
                    x = fx + max(1, int(s)) + i * cell + xx
                    y = fy + j * cell + yy + (1 if i >= 2 and n >= 32 else 0)   # a little wave
                    if 0 <= x < n and 0 <= y < n: img[y][x] = 'W' if (i + j) % 2 == 0 else 'b'
    # the outline: black wherever a painted pixel meets nothing
    out = [row[:] for row in img]
    for y in range(n):
        for x in range(n):
            if img[y][x] is None:
                near = any(0 <= x + ox < n and 0 <= y + oy < n and img[y + oy][x + ox] not in (None,) for ox, oy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
                if near: out[y][x] = 'k'
    im = Image.new('RGBA', (n, n), (0, 0, 0, 0))
    for y in range(n):
        for x in range(n):
            if out[y][x]: im.putpixel((x, y), PAL[out[y][x]])
    return im

i32, i16 = draw(32), draw(16)
sizes = [(16, i16), (32, i32), (48, i16.resize((48, 48), Image.NEAREST)), (64, i32.resize((64, 64), Image.NEAREST)), (256, i32.resize((256, 256), Image.NEAREST))]
# an .ico of PNG images
blobs = []
for n, im in sizes:
    b = io.BytesIO(); im.save(b, 'PNG'); blobs.append(b.getvalue())
with open(os.path.join(HERE, 'sprocket.ico'), 'wb') as f:
    f.write(struct.pack('<HHH', 0, 1, len(sizes)))
    off = 6 + 16 * len(sizes)
    for (n, _), b in zip(sizes, blobs):
        f.write(struct.pack('<BBBBHHII', n % 256, n % 256, 0, 0, 1, 32, len(b), off)); off += len(b)
    for b in blobs: f.write(b)
with open(os.path.join(HERE, '..', 'src', 'icon_data.h'), 'w') as f:
    f.write('// generated by tools/make_icon.py: the 32x32 icon, RGBA bytes as little-endian words\n#pragma once\n')
    f.write('static const unsigned int k_icon32[32 * 32] = {\n')
    px = list(i32.getdata())
    for y in range(32):
        f.write('    ' + ', '.join('0x%08xu' % (p[3] << 24 | p[2] << 16 | p[1] << 8 | p[0]) for p in px[y * 32:(y + 1) * 32]) + ',\n')
    f.write('};\n')
prev = Image.new('RGBA', (32 * 8 + 16 * 8 + 32 + 16 + 40, 32 * 8 + 16), (0, 128, 128, 255))   # a teal desktop
prev.paste(i32.resize((256, 256), Image.NEAREST), (8, 8), i32.resize((256, 256), Image.NEAREST))
prev.paste(i16.resize((128, 128), Image.NEAREST), (272, 8), i16.resize((128, 128), Image.NEAREST))
prev.paste(i32, (408, 8), i32); prev.paste(i16, (408, 48), i16)
prev.save(os.path.join(HERE, 'icon_preview.png'))
print('icon written')
